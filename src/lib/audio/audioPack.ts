import { audioService, SPEECH_MAX_TEXTS, type SpeechResult } from '@/api/services/audioService'
import { clipUrl, getAudioInfo } from '@/lib/audio/audioInfo'
import { deleteClips, hasClip, keepClipsPersistent, loadClip } from '@/lib/audio/clipCache'
import { clipHash, sentences } from '@/lib/audio/speechText'

export interface PackProgress {
  /** Clips saved in the browser so far. */
  saved: number
  total: number
}

export interface PackResult extends PackProgress {
  /** Clips that do not exist yet (guests cannot have them generated). */
  missing: number
}

/** Downloads at once from the CDN; small files, so a few in parallel is plenty. */
const PARALLEL_DOWNLOADS = 6
/**
 * The API generates a few clips per request. After a round with no progress
 * (voices busy, or resting a minute after a failure) wait this long before
 * asking again; give up once every delay has been used.
 */
const IDLE_RETRY_DELAYS_MS = [5_000, 20_000, 45_000]

function sleep(ms: number, signal?: AbortSignal): Promise<void> {
  return new Promise((resolve, reject) => {
    const timer = setTimeout(resolve, ms)
    signal?.addEventListener('abort', () => {
      clearTimeout(timer)
      reject(signal.reason)
    }, { once: true })
  })
}

interface PackEntry {
  text: string
  urls: string[]
}

async function packEntries(texts: readonly string[]): Promise<PackEntry[] | null> {
  const info = await getAudioInfo()
  if (!info.enabled) return null
  const unique = [...new Set(texts)]
  return Promise.all(
    unique.map(async (text) => ({
      text,
      urls: await Promise.all(sentences(text).map(async (s) => clipUrl(info, await clipHash(s)))),
    })),
  )
}

const allUrls = (entries: PackEntry[]) => [...new Set(entries.flatMap((e) => e.urls))]

/** How much of a pack is already saved (for "Downloaded" / "12 of 300"). */
export async function packStatus(texts: readonly string[]): Promise<PackProgress | null> {
  const entries = await packEntries(texts)
  if (!entries) return null
  const urls = allUrls(entries)
  const saved = (await Promise.all(urls.map(hasClip))).filter(Boolean).length
  return { saved, total: urls.length }
}

async function inBatches<T>(items: T[], size: number, run: (item: T) => Promise<void>, signal?: AbortSignal) {
  for (let i = 0; i < items.length; i += size) {
    signal?.throwIfAborted()
    await Promise.all(items.slice(i, i + size).map(run))
  }
}

type ClipApi = (texts: string[]) => Promise<SpeechResult>

/**
 * Asks `api` where the clips of `entries` are, SPEECH_MAX_TEXTS texts per
 * request, and downloads every entry whose clips are all listed. Counts the
 * entry's saved-clip names as done once its clips are in (they may be the
 * fallback voice's).
 */
async function fetchListed(entries: PackEntry[], api: ClipApi, done: Set<string>, report: () => void, signal?: AbortSignal) {
  for (let i = 0; i < entries.length; i += SPEECH_MAX_TEXTS) {
    signal?.throwIfAborted()
    const batch = entries.slice(i, i + SPEECH_MAX_TEXTS)
    const result = await api(batch.map((e) => e.text))
    const ready = result.items.flatMap((item, j) => {
      const entry = batch[j]
      return entry && item.segments.length > 0 && item.segments.every((s) => s.url)
        ? [{ entry, urls: item.segments.map((s) => s.url as string) }]
        : []
    })
    await inBatches(ready, PARALLEL_DOWNLOADS, async ({ entry, urls: served }) => {
      const clips = await Promise.all(served.map((u) => loadClip(u, signal)))
      if (clips.every(Boolean)) entry.urls.forEach((u) => done.add(u))
      report()
    }, signal)
  }
}

/**
 * Saves every clip of `texts` for offline use: the ones that exist, from the
 * CDN URLs the API lists, then (signed-in learners only) the rest generated by
 * the API a few at a time. Resolves with what was saved; abort with `signal`.
 */
export async function downloadPack(
  texts: readonly string[],
  { canGenerate, signal, onProgress }: { canGenerate: boolean; signal?: AbortSignal; onProgress?: (p: PackProgress) => void },
): Promise<PackResult> {
  const entries = await packEntries(texts)
  if (!entries) return { saved: 0, total: 0, missing: 0 }
  void keepClipsPersistent()
  const urls = allUrls(entries)
  const done = new Set<string>()
  const report = () => onProgress?.({ saved: done.size, total: urls.length })
  await inBatches(urls, PARALLEL_DOWNLOADS, async (url) => {
    if (await hasClip(url)) done.add(url)
  }, signal)
  report()

  const unsaved = () => entries.filter((e) => e.urls.some((u) => !done.has(u)))
  await fetchListed(unsaved(), audioService.findClips, done, report, signal)

  let waiting = unsaved()
  let idleRounds = 0
  while (canGenerate && waiting.length > 0 && idleRounds <= IDLE_RETRY_DELAYS_MS.length) {
    signal?.throwIfAborted()
    if (idleRounds > 0) await sleep(IDLE_RETRY_DELAYS_MS[idleRounds - 1], signal)
    const before = done.size
    await fetchListed(waiting.slice(0, SPEECH_MAX_TEXTS), audioService.speak, done, report, signal)
    waiting = unsaved()
    idleRounds = done.size > before ? 0 : idleRounds + 1
  }

  return { saved: done.size, total: urls.length, missing: urls.length - done.size }
}

export async function removePack(texts: readonly string[]): Promise<void> {
  const entries = await packEntries(texts)
  if (entries) await deleteClips(allUrls(entries))
}
