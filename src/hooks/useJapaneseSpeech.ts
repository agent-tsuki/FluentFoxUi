import { useCallback, useEffect, useRef, useState } from 'react'
import type { SpeechVoice } from '@/api/services/audioService'
import { useAuth } from '@/context/AuthContext'
import { getAudioInfo, peekAudioInfo } from '@/lib/audio/audioInfo'
import { clipProgress, playClips, stopClips, unlockClipPlayback, unlockOnNextGesture, type PlaybackProgress } from '@/lib/audio/clipPlayer'
import { loadSpeech } from '@/lib/audio/loadSpeech'
import { IS_DEV } from '@/lib/config'

/** Playback callbacks, e.g. the answer timer's `audioStart` / `audioStop`, so listening time is not counted as answer time. */
export interface SpeechPlaybackHandlers {
  /** The voice started speaking. */
  onStart?: () => void
  /** Speech finished, failed or was cut off by the next `speak`. */
  onEnd?: () => void
}

export interface SpeakOptions extends SpeechPlaybackHandlers {
  /** A listening character's voice (cast key such as "f1", or "alt"): the API's voice for it, else a matching browser voice. */
  voice?: SpeechVoice
  /**
   * Called instead of falling back to the browser voice when the voice's clip
   * does not exist yet (or did not arrive in time), e.g. a listening voice an
   * admin just changed: its clips are generated afresh. `onEnd` follows.
   */
  onMissing?: () => void
}

export type { PlaybackProgress }

/** The browser voice's pace at rate 0.8, for guessing progress when it reports no word boundaries. */
const BROWSER_MS_PER_CHAR = 190
/** System voices that sound male (macOS, Windows, Android names), for male cast keys. */
const MALE_VOICE = /otoya|hattori|ichiro|keita|daichi|naoki|eddy|reed|rocko|grandpa|male/i
/** Pitches that tell the cast apart when the browser has few Japanese voices: by the key's number (f1, f2…). */
const FEMALE_PITCHES = [1, 1.15, 0.92, 1.25, 1.05]
const MALE_PITCHES = [0.75, 0.62, 0.85, 0.55, 0.7]

/**
 * The browser voice and pitch for a speech voice: "main" is the default
 * voice; a male cast key ("m1", or "alt") prefers a male system voice, and
 * pitch keeps the cast's voices apart on systems with only one.
 */
export function browserVoiceFor(
  key: string,
  main: SpeechSynthesisVoice | null,
  japanese: readonly SpeechSynthesisVoice[],
): { voice: SpeechSynthesisVoice | null; pitch: number } {
  if (key === 'main') return { voice: main, pitch: 1 }
  const male = key === 'alt' || key.startsWith('m')
  const n = Math.max(0, Number(key.replace(/\D/g, '') || 1) - 1)
  const pitches = male ? MALE_PITCHES : FEMALE_PITCHES
  const pitch = pitches[n % pitches.length]
  if (!male) return { voice: main, pitch }
  const maleVoice = japanese.find((v) => MALE_VOICE.test(v.name))
  // A male system voice already sounds male: only nudge its pitch for the second, third… man.
  return maleVoice ? { voice: maleVoice, pitch: 1 + (pitch - MALE_PITCHES[0]) / 2 } : { voice: main, pitch }
}

/**
 * How long to wait for a clip before using the browser voice instead. A clip
 * on the CDN arrives in well under a second; a brand-new one is generated by
 * the API, which can take several seconds on its first request, and the
 * learner sees a spinner on the speaker meanwhile (`loadingText`). This covers
 * the API's worst case (a 3 s wait for a free voice plus 11 s to render).
 */
const CLIP_WAIT_MS = 15_000
/** Loading this fast shows no spinner, so cached clips play without a flicker. */
const SPINNER_DELAY_MS = 150

const synthesisSupported = () => typeof window !== 'undefined' && 'speechSynthesis' in window

/**
 * Speaks Japanese. Recorded clips (VOICEVOX, generated once on the API and
 * served by the CDN, kept in the browser cache) come first; the browser's
 * built-in voice (Web Speech API) is the fallback when a clip cannot be had.
 * `loadingText` is the text whose clip is still loading, for a spinner on its
 * speaker button. `supported` is false only where neither voice exists.
 * `progress()` says how far the current speech is (polled while it plays, to
 * highlight the words being said).
 */
export function useJapaneseSpeech(): {
  supported: boolean
  speak: (text: string, options?: SpeakOptions) => void
  loadingText: string | null
  progress: () => PlaybackProgress | null
} {
  const [voice, setVoice] = useState<SpeechSynthesisVoice | null>(null)
  const [japaneseVoices, setJapaneseVoices] = useState<SpeechSynthesisVoice[]>([])
  // The browser voice now speaking: when it started and the last word it reported.
  const browser = useRef<{ text: string; started: number; charIndex: number } | null>(null)
  const [clipsEnabled, setClipsEnabled] = useState(() => peekAudioInfo()?.enabled ?? false)
  const { user } = useAuth()
  const canGenerate = Boolean(user?.emailVerified)
  const request = useRef(0)
  const [loadingText, setLoadingText] = useState<string | null>(null)
  const synthesis = synthesisSupported()

  useEffect(() => {
    unlockOnNextGesture()
    let cancelled = false
    void getAudioInfo().then((info) => !cancelled && setClipsEnabled(info.enabled))
    return () => {
      cancelled = true
    }
  }, [])

  useEffect(() => {
    if (!synthesis) return
    // Voices load asynchronously in Chrome; pick one when the list arrives.
    const pick = () => {
      const voices = window.speechSynthesis.getVoices()
      const main = voices.find((v) => v.lang === 'ja-JP') ?? voices.find((v) => v.lang.startsWith('ja')) ?? null
      setVoice(main)
      setJapaneseVoices(voices.filter((v) => v.lang.startsWith('ja')))
    }
    pick()
    window.speechSynthesis.addEventListener('voiceschanged', pick)
    return () => window.speechSynthesis.removeEventListener('voiceschanged', pick)
  }, [synthesis])

  const speakWithBrowser = useCallback(
    (text: string, handlers?: SpeakOptions) => {
      if (!synthesis) {
        handlers?.onEnd?.()
        return
      }
      window.speechSynthesis.cancel()
      const utterance = new SpeechSynthesisUtterance(text)
      utterance.lang = 'ja-JP'
      utterance.rate = 0.8
      const chosen = browserVoiceFor(handlers?.voice ?? 'main', voice, japaneseVoices)
      if (chosen.voice) utterance.voice = chosen.voice
      utterance.pitch = chosen.pitch
      const state = { text, started: performance.now(), charIndex: -1 }
      browser.current = state
      utterance.onstart = () => {
        state.started = performance.now()
        handlers?.onStart?.()
      }
      utterance.onboundary = (e) => {
        state.charIndex = e.charIndex + (e.charLength ?? 0)
      }
      const end = () => {
        if (browser.current === state) browser.current = null
        handlers?.onEnd?.()
      }
      utterance.onend = end
      utterance.onerror = end
      window.speechSynthesis.speak(utterance)
    },
    [synthesis, voice, japaneseVoices],
  )

  const progress = useCallback((): PlaybackProgress | null => {
    const clips = clipProgress()
    if (clips) return clips
    const b = browser.current
    if (!b) return null
    const length = Math.max(1, b.text.length)
    const fraction = b.charIndex >= 0 ? b.charIndex / length : (performance.now() - b.started) / (length * BROWSER_MS_PER_CHAR)
    return { part: 0, parts: 1, fraction: Math.min(0.98, fraction) }
  }, [])

  const speak = useCallback(
    (text: string, handlers?: SpeakOptions) => {
      const id = ++request.current
      stopClips()
      setLoadingText(null)
      browser.current = null
      if (synthesis) window.speechSynthesis.cancel()
      if (!clipsEnabled) {
        if (IS_DEV) console.info(`[audio] "${text}" → browser voice: recorded audio is off (reload after changing the API's audio settings)`)
        speakWithBrowser(text, handlers)
        return
      }
      unlockClipPlayback() // Must run inside the tap, before anything async.

      let settled = false
      const spinner = window.setTimeout(() => !settled && id === request.current && setLoadingText(text), SPINNER_DELAY_MS)
      const settle = () => {
        settled = true
        window.clearTimeout(spinner)
        window.clearTimeout(timer)
        if (id === request.current) setLoadingText(null)
      }
      const fallback = () => {
        if (settled || id !== request.current) return
        settle()
        if (handlers?.onMissing) {
          handlers.onMissing()
          handlers.onEnd?.()
          return
        }
        speakWithBrowser(text, handlers)
      }
      const timer = window.setTimeout(() => {
        if (IS_DEV && !settled) console.info(`[audio] "${text}" → browser voice now: the clip took over ${CLIP_WAIT_MS} ms (it is still saved for next time)`)
        fallback()
      }, CLIP_WAIT_MS)
      loadSpeech(text, { canGenerate, voice: handlers?.voice })
        .then(async (clips) => {
          if (settled || id !== request.current) return
          if (!clips) return fallback()
          settle()
          const played = await playClips(clips, handlers)
          // Autoplay refused (no prior tap): the browser voice may still be allowed.
          if (!played && id === request.current) speakWithBrowser(text, handlers)
        })
        .catch((error: unknown) => {
          if (IS_DEV) console.info(`[audio] "${text}" → browser voice: request failed`, error)
          fallback()
        })
    },
    [clipsEnabled, canGenerate, synthesis, speakWithBrowser],
  )

  return { supported: synthesis || clipsEnabled, speak, loadingText, progress }
}
