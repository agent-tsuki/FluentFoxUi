/**
 * Writes public/sitemap.xml from the real course data, so every public lesson
 * page is listed and nothing is invented. Run after course content changes:
 *
 *   npm run sitemap
 *
 * Only pages a signed-out visitor can open are listed. Practice, quizzes, tests,
 * reviews and account pages need sign-in and are blocked in public/robots.txt.
 */
import { readdirSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { HIRAGANA_UNITS } from '@/lib/content/kana/hiraganaUnits'
import { KATAKANA_UNITS } from '@/lib/content/kana/katakanaUnits'
import { kanaBasePath } from '@/lib/content/kana/scriptIds'
import { KANJI_BASE, availableKanjiLevels, kanjiLevelPath } from '@/lib/content/kanji/levels'
import { HOW_GRADING_WORKS_PATH } from '@/lib/learn/paths'
import n5Index from '@/lib/content/kanji/generated/n5.index.json'
import n4Index from '@/lib/content/kanji/generated/n4.index.json'

const SITE = 'https://foxsensei.com'
const ROOT = path.resolve(import.meta.dirname, '../..')

interface Entry {
  path: string
  priority: number
  changefreq: 'weekly' | 'monthly' | 'yearly'
}

interface KanjiIndex {
  units: { id: string }[]
  rows: { char: string }[]
}

const KANJI_INDEX: Record<string, KanjiIndex> = { n5: n5Index, n4: n4Index }

const entries: Entry[] = [
  { path: '/', priority: 1, changefreq: 'weekly' },
  { path: '/classes', priority: 0.6, changefreq: 'weekly' },
  { path: HOW_GRADING_WORKS_PATH, priority: 0.4, changefreq: 'yearly' },
  { path: '/about', priority: 0.4, changefreq: 'yearly' },
  { path: '/terms', priority: 0.2, changefreq: 'yearly' },
  { path: '/privacy', priority: 0.2, changefreq: 'yearly' },
]

// Kana: course pages, then one page per unit.
for (const [script, units] of [['hiragana', HIRAGANA_UNITS], ['katakana', KATAKANA_UNITS]] as const) {
  const base = kanaBasePath(script)
  entries.push(
    { path: `${base}/chart`, priority: 0.9, changefreq: 'monthly' },
    { path: `${base}/learn`, priority: 0.9, changefreq: 'monthly' },
    { path: `${base}/tests`, priority: 0.5, changefreq: 'monthly' },
    { path: `${base}/downloads`, priority: 0.6, changefreq: 'monthly' },
  )
  for (const unit of units) entries.push({ path: `${base}/unit/${unit.id}`, priority: 0.7, changefreq: 'monthly' })
}

// Kanji: each available level, its units, and every kanji's own page.
for (const level of availableKanjiLevels()) {
  const index = KANJI_INDEX[level]
  if (!index) throw new Error(`No kanji index for available level "${level}"; add it to KANJI_INDEX`)
  const base = kanjiLevelPath(level)
  entries.push(
    { path: base, priority: 0.9, changefreq: 'monthly' },
    { path: `${base}/browse`, priority: 0.6, changefreq: 'monthly' },
    { path: `${base}/tests`, priority: 0.5, changefreq: 'monthly' },
    { path: `${base}/downloads`, priority: 0.5, changefreq: 'monthly' },
  )
  for (const unit of index.units) entries.push({ path: `${base}/unit/${unit.id}`, priority: 0.7, changefreq: 'monthly' })
  for (const row of index.rows) entries.push({ path: `${KANJI_BASE}/${encodeURIComponent(row.char)}`, priority: 0.6, changefreq: 'monthly' })
}

// Grammar: one page per N5 chapter file.
const grammarChapters = readdirSync(path.join(ROOT, 'src/assets/grammar/n5'))
  .map((file) => /^chapter-(\d+)\.mdx$/.exec(file)?.[1])
  .filter((id): id is string => Boolean(id))
  .map(Number)
  .sort((a, b) => a - b)
for (const chapter of grammarChapters) {
  entries.push({ path: `/grammar/n5/${chapter}`, priority: chapter === 1 ? 0.9 : 0.7, changefreq: 'monthly' })
}

const seen = new Set<string>()
const urls = entries
  .filter((entry) => !seen.has(entry.path) && seen.add(entry.path))
  .map((entry) => `  <url>\n    <loc>${SITE}${entry.path}</loc>\n    <changefreq>${entry.changefreq}</changefreq>\n    <priority>${entry.priority.toFixed(1)}</priority>\n  </url>`)

const xml = `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by scripts/seo/generate-sitemap.ts. Do not edit by hand; run npm run sitemap. -->
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${urls.join('\n')}
</urlset>
`

writeFileSync(path.join(ROOT, 'public/sitemap.xml'), xml)
console.log(`public/sitemap.xml: ${urls.length} URLs (${grammarChapters.length} grammar chapters)`)
