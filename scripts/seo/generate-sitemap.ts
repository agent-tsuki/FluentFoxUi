/**
 * Writes public/sitemap.xml from the real course data (scripts/seo/routes.ts),
 * so every public page is listed and nothing is invented. Run after course
 * content changes:
 *
 *   npm run sitemap
 *
 * Only pages a signed-out visitor can open are listed. Practice, quizzes,
 * tests, reviews and account pages need sign-in and are blocked in
 * public/robots.txt. Old unit URLs (/kana/<script>/unit/<id>,
 * /kanji/<level>/unit/<id>) are 301 redirects (vercel.json), so they are left
 * out: a sitemap lists only the pages themselves.
 */
import { writeFileSync } from 'node:fs'
import path from 'node:path'
import { SITE_URL } from '@/lib/seo/titles'
import { seoRoutes } from './routes'

const ROOT = path.resolve(import.meta.dirname, '../..')
const today = new Date().toISOString().slice(0, 10)

const urls = seoRoutes().map(
  (r) => `  <url>\n    <loc>${SITE_URL}${r.path}</loc>\n    <lastmod>${today}</lastmod>\n    <changefreq>${r.changefreq}</changefreq>\n    <priority>${r.priority.toFixed(1)}</priority>\n  </url>`,
)

const xml = `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by scripts/seo/generate-sitemap.ts. Do not edit by hand; run npm run sitemap. -->
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${urls.join('\n')}
</urlset>
`

writeFileSync(path.join(ROOT, 'public/sitemap.xml'), xml)
console.log(`public/sitemap.xml: ${urls.length} URLs`)
